const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { _electron } = require(path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
(async () => {
  const root = path.resolve(__dirname, '..');
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'game-media-'));
  const folder = path.join(temp, 'lesson');
  await require('./phase6g-fixture.cjs')(folder, 'game-media-test');
  const evidence = path.join(root, 'docs/game-media-evidence');
  await fs.mkdir(evidence, { recursive: true });
  const app = await _electron.launch({ executablePath: require('electron'), cwd: root, args: [root, '--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', `--user-data-dir=${path.join(temp, 'profile')}`] });
  const page = await app.firstWindow();
  page.setDefaultTimeout(20000);
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  const button = name => page.getByRole('button', { name, exact: true });
  try {
    await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0, checkboxChecked: false }); });
    await button('Mastery').click();
    await button('Discovery').waitFor();
    await page.getByRole('region', { name: 'Camera', exact: true }).waitFor();
    await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }); }, folder);
    await button('Open lesson media').click();
    const asset = page.locator('.lesson-pool-asset').filter({ hasText: 'Character artwork' });
    await asset.click();
    await button('Add to Mastery').click();
    await button('Save lesson').click();
    await page.waitForFunction(() => !document.querySelector('.lesson-project-title').textContent.includes('Unsaved'));
    const saved = JSON.parse(await fs.readFile(path.join(folder, 'project.json'), 'utf8'));
    assert.equal(saved.activities.find(a => a.id === 'boss').config.cardLibrary.at(-1).image, 'asset:reward-art');
    await page.screenshot({ path: path.join(evidence, 'mastery-desktop.png') });
    await button('Launch Final Boss Hero').click();
    const present = app.windows().find(p => p !== page) || await app.waitForEvent('window');
    await page.getByText('Ready in Present', { exact: true }).waitFor();
    await page.getByRole('region', { name: 'Camera', exact: true }).waitFor();
    await page.getByRole('region', { name: 'Translation', exact: true }).waitFor();
    await button('Turn camera on').click();
    await present.locator('[data-camera-live="true"]').waitFor();
    await present.screenshot({ path: path.join(evidence, 'mastery-present-camera.png') });
    assert.equal(await button('Add to Mastery').isDisabled(), true);
    await button('Return to setup').click();
    await button('Launch Final Boss Hero').waitFor();
    await button('Challenge').click();
    await asset.click();
    await button('Use as background').click();
    await button('Launch Language Snake').click();
    await page.getByText('Ready in Present', { exact: true }).waitFor();
    await present.locator('[data-camera-live="true"]').waitFor();
    await present.screenshot({ path: path.join(evidence, 'challenge-present-camera.png') });
    await button('Turn camera off').click();
    await button('Discovery').click();
    await page.getByRole('navigation', { name: 'Lesson phases' }).waitFor();
    await button('Mastery').click();
    await page.setViewportSize({ width: 640, height: 900 });
    await page.screenshot({ path: path.join(evidence, 'mastery-narrow.png') });
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    assert.equal(overflow, false, 'No page horizontal overflow');
    assert.deepEqual(errors, []);
    await fs.writeFile(path.join(evidence, 'results.json'), JSON.stringify({ passed: ['Media pool assignment and persistence', 'Mastery launch using pool media', 'Live setup guard and flush', 'Challenge pool background and launch', 'Discovery navigation from running game', 'Camera and translation controls mounted', 'Narrow page without overflow'], errors }, null, 2));
    console.log('PASS game media native workflow');
  } catch (error) { await page.screenshot({ path: path.join(evidence, 'failure.png') }); throw error; }
  finally { await app.evaluate(({ app }) => app.exit(0)).catch(() => {}); }
})().catch(error => { console.error(error); process.exitCode = 1; });
