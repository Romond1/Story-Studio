/* Real Electron acceptance: only native file picker results are substituted. */
const { _electron } = require(process.env.STORY_STUDIO_PLAYWRIGHT || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const c = require('../dist-test/shared/lesson/commands');
(async () => {
  const root = path.resolve(__dirname, '..');
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'story-polish-'));
  const folder = path.join(temp, 'Lesson'), source = path.join(temp, 'source');
  const evidence = path.join(root, 'docs', 'beginning-polish-evidence');
  await fs.mkdir(path.join(folder, 'assets'), { recursive: true });
  await fs.mkdir(path.join(source, 'Nested'), { recursive: true });
  await fs.mkdir(evidence, { recursive: true });
  for (const file of ['files.png', 'drop.png', 'root.png', 'dialog.png', 'Nested/folder.png']) await fs.copyFile(path.join(root, 'assets', 'Splash Screen', 'Story.png'), path.join(source, file));
  let project = c.createLesson('A little wonder');
  project = c.insertScene(project, 'story', c.createScene('Welcome to the story')).project;
  project = c.insertScene(project, 'activation', c.createScene('Time to discover')).project;
  await fs.writeFile(path.join(folder, 'project.json'), JSON.stringify(project));
  const app = await _electron.launch({ executablePath: require('electron'), cwd: root, args: [root, `--user-data-dir=${path.join(temp, 'profile')}`] });
  const results = [], errors = []; let page;
  const pass = name => { results.push(name); console.log('PASS', name); };
  try {
    page = await app.firstWindow(); page.setDefaultTimeout(10000);
    page.on('pageerror', e => errors.push(String(e)));
    page.on('dialog', d => d.accept());
    const button = name => page.getByRole('button', { name, exact: true });
    const choose = files => app.evaluate(({ dialog }, files) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: files }); }, files);
    const resize = (width, height) => app.evaluate(({ BrowserWindow }, size) => { const w = BrowserWindow.getAllWindows()[0]; w.setMinimumSize(320, 400); w.setSize(...size); }, [width, height]);
    const shot = async name => { await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))); await page.screenshot({ path: path.join(evidence, name + '.png'), fullPage: name !== 'workspace-narrow' }); };
    await button('Adventure').waitFor();
    await resize(1440, 1000);
    assert.equal(await page.locator('.beginning-primary button').count(), 4);
    assert.equal(await page.locator('.beginning-secondary button').count(), 3);
    await page.waitForFunction(() => [...document.querySelectorAll('.beginning img')].every(i => i.complete && i.naturalWidth));
    await shot('beginning-desktop');
    await resize(390, 844); await shot('beginning-mobile');
    const visualAudit = await page.evaluate(() => ({
      horizontalOverflow: document.documentElement.scrollWidth > innerWidth,
      missingAlt: document.querySelectorAll('.beginning img:not([alt])').length,
      clippedCards: [...document.querySelectorAll('.beginning-card')].filter(el => { const r = el.getBoundingClientRect(); return r.left < 0 || r.right > innerWidth; }).length,
      tinyText: [...document.querySelectorAll('.beginning span, .beginning p')].filter(el => parseFloat(getComputedStyle(el).fontSize) < 11).length,
    }));
    assert.deepEqual(visualAudit, { horizontalOverflow: false, missingAlt: 0, clippedCards: 0, tinyText: 0 });
    await fs.writeFile(path.join(evidence, 'visual-audit.json'), JSON.stringify(visualAudit, null, 2));
    pass('Startup launcher: seven icons, four primary cards, responsive layout');
    await resize(1440, 1000);
    for (const [name, game] of [['Challenge', 'Language Snake'], ['Mastery', 'Final Boss Hero']]) {
      await button(name).click(); await page.getByRole('heading', { name, exact: true }).waitFor();
      await button(`Launch ${game}`).waitFor();
      assert.equal(app.windows().filter(window => !window.isClosed()).length, 1, 'Choosing a module does not auto-launch a game');
      await button('Back to Beginning').click();
    }
    await button('Users').click(); await page.getByRole('heading', { name: 'Users', exact: true }).waitFor();
    await page.getByText('Coming soon', { exact: true }).waitFor(); await button('Back to Beginning').click();
    pass('Challenge and Mastery open shared game selection; Users opens its placeholder; all return');
    await button('Settings').click(); await page.getByRole('dialog').waitFor(); await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({ state: 'hidden' }); pass('Settings opens and closes existing audio workspace');
    await button('Discovery').click();
    await page.getByLabel('Edit canvas', { exact: true }).waitFor();
    assert.equal(await page.locator('.lesson-welcome').count(), 0);
    await button('Add Card').click();
    await page.getByLabel('Card text', { exact: true }).fill('Created before choosing a folder');
    await choose([path.join(source, 'files.png')]); await button('Import files').click();
    await page.getByRole('listbox', { name: 'Project media' }).getByRole('option', { name: /files.png/ }).waitFor();
    await app.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] }); });
    await button('Save').click();
    await button('Save').waitFor();
    assert.equal(await page.getByLabel('Card text', { exact: true }).inputValue(), 'Created before choosing a folder');
    const draftSaved = path.join(temp, 'Saved-draft'); await fs.mkdir(draftSaved);
    await choose([draftSaved]); await button('Save').click();
    await page.waitForFunction(() => document.querySelector('.lesson-status')?.textContent.includes('Lesson saved.'));
    const draftData = JSON.parse(await fs.readFile(path.join(draftSaved, 'project.json'), 'utf8'));
    assert.equal(draftData.sequences.activation.length, 1);
    assert.equal(Object.values(draftData.cards)[0].faces[0].text, 'Created before choosing a folder');
    await fs.access(path.join(draftSaved, draftData.assets[0].relativePath));
    pass('Direct blank Discovery supports cards and imports before Save; cancel preserves edits and first Save copies media');
    await choose([folder]); await button('Open project').click();
    assert.equal(await button('Edit').getAttribute('aria-pressed'), 'true');
    assert.equal(await button('Discovery').getAttribute('aria-pressed'), 'true');
    await page.getByLabel('Edit canvas', { exact: true }).waitFor(); pass('Discovery entry opens loaded lesson in Discovery Edit');
    await page.getByRole('link', { name: 'Story Studio', exact: true }).click(); await button('Adventure').click();
    assert.equal(await button('Adventure').getAttribute('aria-pressed'), 'true');
    assert.equal(await button('Edit').getAttribute('aria-pressed'), 'true'); pass('Adventure entry resumes loaded lesson in Adventure Edit');
    await button('Edit').click();
    await button('Media bins').click(); await button('New bin').click();
    await page.getByLabel('New bin name', { exact: true }).fill('Discovery'); await button('Create bin').click();
    const bin = await page.getByLabel('Bin', { exact: true }).inputValue(); assert.ok(bin);
    await choose([path.join(source, 'files.png')]); await button('Import files').click();
    await page.getByRole('listbox', { name: 'Project media' }).getByRole('option', { name: /files.png/ }).waitFor();
    await button('Media filters').click(); await choose([path.join(source, 'Nested')]); await button('Import folder').click();
    await page.getByRole('listbox', { name: 'Project media' }).getByRole('option', { name: /folder.png/ }).waitFor();
    await button('Reset filters').click();
    assert.equal(await page.getByLabel('Bin', { exact: true }).inputValue(), bin);
    await button('Media filters').click(); await button('Media bins').click();
    const bounds = await page.locator('.lesson-pool').boundingBox();
    const cdp = await page.context().newCDPSession(page);
    const data = { items: [], files: [path.join(source, 'drop.png')], dragOperationsMask: 1 };
    const point = { x: bounds.x + bounds.width / 2, y: bounds.y + bounds.height / 2 };
    await cdp.send('Input.dispatchDragEvent', { type: 'dragEnter', ...point, data });
    await cdp.send('Input.dispatchDragEvent', { type: 'drop', ...point, data });
    await page.getByRole('listbox', { name: 'Project media' }).getByRole('option', { name: /drop.png/ }).waitFor();
    await page.getByLabel('Edit canvas', { exact: true }).click({ button: 'right' });
    await page.getByRole('menuitem', { name: 'Add Image', exact: true }).click();
    await choose([path.join(source, 'dialog.png')]); await button('Import images').click();
    await page.getByRole('dialog', { name: 'Add Image' }).getByRole('button', { name: 'dialog.png', exact: true }).waitFor();
    await button('Cancel').click();
    await button('Save').click();
    await page.waitForFunction(() => !document.querySelector('.lesson-project-title').textContent.includes('Unsaved'));
    let saved = JSON.parse(await fs.readFile(path.join(folder, 'project.json'), 'utf8'));
    for (const name of ['files.png', 'drop.png', 'dialog.png']) assert.equal(saved.assets.find(a => a.originalName === name).binId, bin);
    const importedFolder = saved.mediaBins.find(b => b.name === 'Nested'); assert.equal(importedFolder.parentId, bin);
    assert.equal(saved.assets.find(a => a.originalName === 'folder.png').binId, importedFolder.id);
    pass('File, folder, image-dialog and OS-file drop imports persist directly in active bin; Reset filters retains destination');
    await button('Media bins').click(); await page.getByLabel('Bin', { exact: true }).selectOption('');
    await choose([path.join(source, 'root.png')]); await button('Import files').click();
    await page.getByRole('listbox', { name: 'Project media' }).getByRole('option', { name: /root.png/ }).waitFor(); await button('Save').click();
    await page.waitForFunction(() => !document.querySelector('.lesson-project-title').textContent.includes('Unsaved'));
    saved = JSON.parse(await fs.readFile(path.join(folder, 'project.json'), 'utf8'));
    assert.equal(saved.assets.find(a => a.originalName === 'root.png').binId, undefined); pass('General media import stays at root');
    await page.getByLabel('Bin', { exact: true }).selectOption(bin); await button('Media bins').click();
    await shot('workspace-desktop'); await resize(700, 1000); await shot('workspace-narrow'); await resize(1440, 1000);
    await page.getByLabel('Scene title', { exact: true }).fill('Unsaved discovery');
    await page.getByRole('link', { name: 'Story Studio', exact: true }).click(); await button('Adventure').click(); await button('Edit').click();
    assert.equal(await page.getByLabel('Scene title', { exact: true }).inputValue(), 'Unsaved discovery');
    await button('Media bins').click();
    assert.equal(await page.getByLabel('Bin', { exact: true }).inputValue(), bin);
    pass('Beginning navigation preserves unsaved scene edits and active bin');
    await button('Open Present').click();
    await page.waitForTimeout(700);
    assert.ok(app.windows().length >= 2); pass('Present still opens from rebuilt workspace');
    const storyOnlyFolder = path.join(temp, 'Story-only'); await fs.mkdir(storyOnlyFolder);
    const storyOnly = { ...project, id: 'story-only', sequences: { ...project.sequences, activation: [] } };
    await fs.writeFile(path.join(storyOnlyFolder, 'project.json'), JSON.stringify(storyOnly));
    await page.getByRole('link', { name: 'Story Studio', exact: true }).click(); await button('Discovery').click();
    await choose([storyOnlyFolder]); await button('Open project').click();
    await page.getByText('Lesson opened.', { exact: true }).waitFor();
    assert.equal(await button('Discovery').getAttribute('aria-pressed'), 'true');
    await button('Adventure').click();
    assert.equal(await button('Adventure').getAttribute('aria-pressed'), 'true');
    assert.ok(await page.locator('[data-entry-id]').count());
    pass('Adventure tab recovers from an empty Discovery launch');
    await page.getByRole('link', { name: 'Story Studio', exact: true }).click(); await button('Legacy').click();
    await page.waitForURL(/legacy=1/); await page.locator('.beginning').waitFor({ state: 'detached' });
    pass('Legacy uses explicit legacy entry route');
    await button('Story Studio home').click();
    await page.getByRole('heading', { name: 'Story Studio', exact: true }).waitFor();
    assert.equal(await page.getByText('Where will your lesson go?', { exact: true }).count(), 0);
    pass('Legacy home returns to the simplified Story Studio chooser');
    await button('Legacy').click(); await button('Story Studio home').waitFor(); if (await button('Switch to Edit').isVisible()) await button('Switch to Edit').click();
    const legacyFolder = path.join(temp, 'Legacy-test'); await fs.mkdir(legacyFolder);
    await choose([legacyFolder]); await button('Create Project').click();
    await page.waitForTimeout(300); if (await button('Switch to Edit').isVisible()) await button('Switch to Edit').click();
    await choose([path.join(source, 'files.png')]); await button('Import Media').click();
    await page.locator('.pool-asset').first().waitFor();
    await button('Story Studio home').click();
    await page.getByRole('heading', {name:'Unsaved Changes',exact:true}).waitFor();
    await button('Cancel').click(); assert.match(page.url(), /legacy=1/);
    await button('Story Studio home').click(); await button('Discard').click();
    await page.getByRole('heading', {name:'Story Studio',exact:true}).waitFor();
    pass('Legacy Edit home uses the existing unsaved-change guard; Cancel stays and Discard returns');
    await button('Adventure').click();
    await page.getByLabel('Edit canvas', { exact: true }).waitFor();
    assert.equal(await page.locator('.lesson-welcome').count(), 0);
    assert.equal(await button('Adventure').getAttribute('aria-pressed'), 'true');
    await button('Add Card').click();
    await page.getByLabel('Card text', { exact: true }).fill('Blank Story is ready');
    pass('Fresh Adventure entry opens a blank scene with immediate authoring');
    assert.deepEqual(errors, []);
    await fs.writeFile(path.join(evidence, 'results.json'), JSON.stringify({ results, errors }, null, 2));
  } catch (error) { if (page) await page.screenshot({ path: path.join(evidence, 'failure.png') }).catch(() => {}); throw error; }
  finally { if (page && !page.isClosed()) await page.evaluate(() => window.appApi.forceClose()).catch(() => {}); await app.close().catch(() => {}); }
})().catch(error => { console.error(error); process.exitCode = 1; });
